# Installs an Edge Impulse "Arduino library" export into the Q-Kart sketch.
#
# The library is unpacked into sketch/libraries/<name>_inferencing, the sketch
# profile (sketch.yaml) gets a `- dir:` entry for it and model_config.h is
# rewritten so sketch.ino includes the model. The sketch is compiled the next
# time the app starts.
#
# Also usable from a terminal (on your computer or on the board):
#   python3 q-kart/python/model_installer.py ~/Downloads/my-project-arduino-1.0.1.zip
#   python3 q-kart/python/model_installer.py --remove

import io
import os
import re
import shutil
import sys
import zipfile

APP_DIR = os.environ.get("QKART_APP_DIR") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKETCH_DIR = os.path.join(APP_DIR, "sketch")
LIB_DIR = os.path.join(SKETCH_DIR, "libraries")
MAX_UNPACKED = 200 * 1024 * 1024

BASE_LIBRARIES = [
    "Arduino_Modulino (0.7.0)",
    "dependency: ArduinoGraphics (1.1.4)",
    "dependency: Arduino_HS300x (1.0.0)",
    "dependency: Arduino_LPS22HB (1.0.2)",
    "dependency: Arduino_LSM6DSOX (1.1.2)",
    "dependency: Arduino_LTR381RGB (1.0.0)",
    "dependency: STM32duino VL53L4CD (1.0.5)",
    "dependency: STM32duino VL53L4ED (1.0.1)",
]

NO_MODEL_CONFIG = """// Generated by python/model_installer.py — do not edit by hand.
//
// No Edge Impulse model is installed yet: the sketch streams the Modulino
// Movement data (for training and steering) but does not classify gestures.
// Install a model from the Motion Lab page (/train.html) or with
//   python3 python/model_installer.py path/to/ei-arduino-library.zip
#pragma once
#define QKART_HAS_MODEL 0
"""


class InstallError(Exception):
    pass


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def write_sketch_yaml(lib_folder=None):
    lines = ["profiles:", "  default:", "    platforms:", "      - platform: arduino:zephyr", "    libraries:"]
    lines += [f"      - {lib}" for lib in BASE_LIBRARIES]
    if lib_folder:
        lines.append(f"      - dir: libraries/{lib_folder}")
    lines.append("default_profile: default")
    _write(os.path.join(SKETCH_DIR, "sketch.yaml"), "\n".join(lines) + "\n")


def write_model_config(header=None, name=None):
    if not header:
        _write(os.path.join(SKETCH_DIR, "model_config.h"), NO_MODEL_CONFIG)
        return
    safe_name = re.sub(r'[^A-Za-z0-9 _\-.]', "", name or "")[:64]
    text = (
        "// Generated by python/model_installer.py — do not edit by hand.\n"
        f"// Edge Impulse model: {safe_name}\n"
        "#pragma once\n"
        "#define QKART_HAS_MODEL 1\n"
        f"#define QKART_EI_HEADER <{header}>\n"
    )
    _write(os.path.join(SKETCH_DIR, "model_config.h"), text)


def installed_model():
    """Returns {"folder", "header", "name"} of the installed library, or None."""
    try:
        with open(os.path.join(SKETCH_DIR, "model_config.h"), encoding="utf-8") as f:
            cfg = f.read()
    except OSError:
        return None
    m = re.search(r"QKART_EI_HEADER <([^>]+)>", cfg)
    if not m or "QKART_HAS_MODEL 1" not in cfg:
        return None
    header = m.group(1)
    label = re.search(r"// Edge Impulse model: (.*)", cfg)
    folder = None
    if os.path.isdir(LIB_DIR):
        for d in os.listdir(LIB_DIR):
            if os.path.isfile(os.path.join(LIB_DIR, d, "src", header)):
                folder = d
    return {"folder": folder, "header": header, "name": label.group(1).strip() if label else header}


def _remove_libraries():
    if os.path.isdir(LIB_DIR):
        for d in os.listdir(LIB_DIR):
            p = os.path.join(LIB_DIR, d)
            if os.path.isdir(p) and d.endswith("_inferencing"):
                shutil.rmtree(p, ignore_errors=True)


def remove_model():
    _remove_libraries()
    write_model_config(None)
    write_sketch_yaml(None)


def _unpack(zf, prefix, staging):
    root = os.path.realpath(staging)
    for info in zf.infolist():
        if not info.filename.startswith(prefix) or info.is_dir():
            continue
        rel = info.filename[len(prefix):]
        dest = os.path.realpath(os.path.join(staging, rel))
        if not dest.startswith(root + os.sep):     # zip-slip guard
            raise InstallError(f"unsafe path in zip: {info.filename}")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with zf.open(info) as src, open(dest, "wb") as out:
            shutil.copyfileobj(src, out)


def install_zip(data):
    """Install from the bytes of an EI Arduino library zip. Returns a summary dict."""
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile as e:
        raise InstallError(f"not a zip file ({e})")
    names = zf.namelist()
    headers = [n for n in names if re.fullmatch(r"(?:[^/]+/)?src/[^/]+_inferencing\.h", n)]
    if not headers:
        raise InstallError("this zip is not an Edge Impulse Arduino library (no src/*_inferencing.h)")
    header_path = headers[0]
    prefix = header_path.split("src/")[0]          # "name_inferencing/" or ""
    header = header_path.rsplit("/", 1)[1]
    folder = header[:-2]                           # "<project>_inferencing"
    if not re.fullmatch(r"[A-Za-z0-9_\-.]+", folder):
        raise InstallError(f"unexpected library name {folder!r}")

    total = sum(i.file_size for i in zf.infolist())
    if total > MAX_UNPACKED:
        raise InstallError("library is unexpectedly large")

    os.makedirs(LIB_DIR, exist_ok=True)
    staging = os.path.join(LIB_DIR, ".staging")
    shutil.rmtree(staging, ignore_errors=True)
    os.makedirs(staging)
    try:
        _unpack(zf, prefix, staging)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise

    name, version = folder[: -len("_inferencing")], ""
    props = os.path.join(staging, "library.properties")
    if os.path.isfile(props):
        with open(props, encoding="utf-8", errors="replace") as f:
            text = f.read()
        m = re.search(r"^name=(.*)$", text, re.M)
        if m:
            name = m.group(1).strip()
        m = re.search(r"^version=(.*)$", text, re.M)
        if m:
            version = m.group(1).strip()

    _remove_libraries()
    os.replace(staging, os.path.join(LIB_DIR, folder))
    write_sketch_yaml(folder)
    write_model_config(header, f"{name} {version}".strip())
    return {"ok": True, "folder": folder, "header": header, "name": name, "version": version}


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--remove":
        remove_model()
        print("Model removed. Restart the app to rebuild the sketch.")
    elif len(sys.argv) == 2:
        with open(sys.argv[1], "rb") as f:
            r = install_zip(f.read())
        print(f"Installed {r['name']} ({r['folder']}). Restart the app to compile it into the sketch.")
    else:
        print("usage: model_installer.py <ei-arduino-library.zip> | --remove")
        sys.exit(2)
